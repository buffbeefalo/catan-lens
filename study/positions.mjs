// Held-out opening positions for the human studies (study/README.md). Deterministic: the same code always gives the
// same file. `node study/positions.mjs` checks study/positions-2026-10-12.json against this generator; `--write`
// creates the file once and refuses to change it afterwards, because reviews refer to these exact positions.
// The selection rule below was fixed before any review and never looks at what either policy would choose.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateBoard } from '../public/board.js';
import { simulateDraft } from '../public/score.js';

export const VERSION = 'positions-2026-10-12';
const FIRST_SEED = 9000000, COUNT = 24, PLAYERS = 4, FORM_SIZE = 8;
const FILE = fileURLToPath(new URL(`./${VERSION}.json`, import.meta.url));

const STATUS = 'No reviews or study sessions have taken place. Recruitment and results are outstanding.';
const CORNERS = 'Corners are numbered 1 to 54, as shown on the review page. In Catan Lens code a corner id is its number minus 1.';
const RULE = [
  'Fixed on 2026-10-12, before any review. The rule never looks at what either policy would choose for a task.',
  'Boards: 4-player base game boards generated by Catan Lens (public/board.js, balanced setup) from seeds 9,000,000 to 9,000,023, one position per seed, in seed order. Seeds 9,000,000 to 9,000,999 are reserved for these studies; no benchmark or test uses them.',
  'Seat: position k (k = 1 to 24) is seat ((k - 1) mod 4) + 1, so seats run 1, 2, 3, 4, 1, 2 and so on.',
  'Task: positions 1 to 4 ask for a first settlement, positions 5 to 8 for a second settlement, and so on, switching every four positions. That gives 12 first and 12 second settlement tasks, three of each for every seat.',
  'Pieces already placed: every settlement placed before the task in snake order (seats 1, 2, 3, 4, then 4, 3, 2, 1), copied from the classic projected opening (public/score.js simulateDraft) for that board. This fixes the position only; nothing about any policy\'s next choice is stored.',
  'Learning study forms: A is P01 to P08, B is P09 to P16, C is P17 to P24. Each form has every seat once for each task.',
];

export function buildPositions() {
  const positions = [];
  for (let k = 0; k < COUNT; k++) {
    const seed = FIRST_SEED + k, seat = (k % PLAYERS) + 1, task = Math.floor(k / PLAYERS) % 2 === 0 ? 'first' : 'second';
    const board = generateBoard({ setup: 'base', seed, balanced: true });
    // Settlements down before the task: the earlier seats' firsts, or every first plus the later seats' seconds.
    const before = task === 'first' ? seat - 1 : 2 * PLAYERS - seat;
    const placed = simulateDraft(board, { players: PLAYERS, seat, cak: false }).slice(0, before)
      .map((d, i) => ({ order: i + 1, seat: d.seat, corner: d.id + 1 }));
    positions.push({ id: `P${String(k + 1).padStart(2, '0')}`, seed, setup: 'base', players: PLAYERS, seat, task,
      hexes: board.hexes.map(h => ({ resource: h.resource, number: h.number })), harbors: { ...board.harbors }, placed });
  }
  const learningForms = Object.fromEntries(['A', 'B', 'C'].map((f, i) => [f, positions.slice(i * FORM_SIZE, (i + 1) * FORM_SIZE).map(p => p.id)]));
  return { kind: 'catan-lens-study-positions', version: VERSION, status: STATUS, generatedBy: 'node study/positions.mjs --write',
    selectionRule: RULE, corners: CORNERS, learningForms, positions };
}

// One line per field (and per rule sentence), so the file stays readable and a diff points at a single position.
const field = ([k, v], pad) => `${pad}${JSON.stringify(k)}: ${JSON.stringify(v)}`;
export function formatPositions({ positions, ...head }) {
  const lines = Object.entries(head).map(([k, v]) => Array.isArray(v) ? `  ${JSON.stringify(k)}: [\n${v.map(s => `    ${JSON.stringify(s)}`).join(',\n')}\n  ]`
    : typeof v === 'object' ? `  ${JSON.stringify(k)}: {\n${Object.entries(v).map(e => field(e, '    ')).join(',\n')}\n  }` : field([k, v], '  '));
  const items = positions.map(p => `    {\n${Object.entries(p).map(e => field(e, '      ')).join(',\n')}\n    }`);
  return `{\n${lines.join(',\n')},\n  "positions": [\n${items.join(',\n')}\n  ]\n}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = formatPositions(buildPositions());
  const saved = existsSync(FILE) ? readFileSync(FILE, 'utf8') : null;
  if (process.argv.includes('--write') && saved === null) { writeFileSync(FILE, out); console.log(`Wrote ${VERSION}.json.`); }
  else if (saved === out) console.log(`${VERSION}.json matches the generator.`);
  else {
    console.error(saved === null ? `${VERSION}.json is missing. Run with --write to create it.`
      : `${VERSION}.json differs from the generator. The positions are frozen once reviews start: never overwrite them; make a new dated file instead.`);
    process.exitCode = 1;
  }
}
